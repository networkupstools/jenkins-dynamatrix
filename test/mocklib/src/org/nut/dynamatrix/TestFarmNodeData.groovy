    /**
     * Get the total count of mock nodes.
     */
    public static int getNodeCount() {
        return FARM_NODES_LABELS.size()
    }

    /**
     * Get all node names available in the mock dataset.
     */
    public static List<String> getNodeNames() {
        return new ArrayList<String>(FARM_NODES_LABELS.keySet())
    }

    /**
     * Get a single NodeData instance for the given node name.
     */
    public static NodeData getNodeData(String nodeName) {
        if (!FARM_NODES_LABELS.containsKey(nodeName)) {
            throw new IllegalArgumentException("Unknown node name: ${nodeName}")
        }
        return new NodeData(nodeName, FARM_NODES_LABELS[nodeName])
    }

    /**
     * Get a Map of nodeName -> NodeData for all nodes or a specific subset.
     */
    public static Map<String, NodeData> getNodeDataMap(Collection<String> nodeNames = null) {
        Map<String, NodeData> result = [:]
        Collection<String> targetNames = nodeNames ?: FARM_NODES_LABELS.keySet()
        targetNames.each { String name ->
            if (FARM_NODES_LABELS.containsKey(name)) {
                result[name] = new NodeData(name, FARM_NODES_LABELS[name])
            }
        }
        return result
    }

    /**
     * Get an initialized NodeCaps object populated with NodeData for all nodes or a specific subset.
     */
    public static NodeCaps getNodeCaps(Collection<String> nodeNames = null, Object script = null) {
        NodeCaps nc = new NodeCaps(script)
        nc.nodeData = getNodeDataMap(nodeNames)
        nc.isInitialized = true
        return nc
    }
